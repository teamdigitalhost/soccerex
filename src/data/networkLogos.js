// Deterministic shuffle so each marquee row carries a different mix while the
// order stays the same between renders and between visitors.
export function shuffleLogos(arr, seed = 1) {
  const a = [...arr]
  let s = seed
  for (let i = a.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280
    const j = Math.floor((s / 233280) * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
